#!/usr/bin/env python3
"""
RG DS edition: the icon beside "RG3DS edition by Rubbed-Genie" under the
title screen (assets/artwork/rg3ds/avatar.png, Rubbed-Genie's GitHub avatar).
Cut to a circle at ICON pixels and written as src/3ds_credit_art.h: RGB plus a
coverage byte a pixel, drawn dimmed beside the developer's logo.

    python scripts/gen_credit_art.py
"""
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
SRC = os.path.join(PORT, "assets", "artwork", "rg3ds", "avatar.png")
OUT = os.path.join(PORT, "src", "3ds_credit_art.h")
ICON = 27          # the logo's height (ART_LOGO_H)
SS = 8             # supersampling for the circle's edge


def main():
    im = Image.open(SRC).convert("RGB").resize((ICON, ICON), Image.LANCZOS)
    mask = Image.new("L", (ICON * SS, ICON * SS), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, ICON * SS - 1, ICON * SS - 1), fill=255)
    mask = mask.resize((ICON, ICON), Image.LANCZOS)
    rgb, a = im.tobytes(), mask.tobytes()
    lines = [
        "/* Generated by scripts/gen_credit_art.py; do not edit. */",
        "#ifndef CTR_CREDIT_ART_H",
        "#define CTR_CREDIT_ART_H",
        "",
        "#define ART_CREDIT_ICON %d" % ICON,
        "/* R, G, B, coverage per pixel, row by row. */",
        "static const u8 sArtCreditIcon[%d] = {" % (ICON * ICON * 4),
    ]
    px = []
    for i in range(ICON * ICON):
        px += [rgb[i * 3], rgb[i * 3 + 1], rgb[i * 3 + 2], a[i]]
    for i in range(0, len(px), 16):
        lines.append("    " + ", ".join("0x%02X" % b for b in px[i:i + 16]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
